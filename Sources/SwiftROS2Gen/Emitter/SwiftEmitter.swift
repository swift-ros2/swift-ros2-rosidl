/// Converts a ``MessageIR`` into the Swift source text for a generated ``ROS2Message`` type.
public enum SwiftEmitter {
    /// ROS type names equal to a Swift standard-library type name. They keep the `Msg`
    /// suffix so the generated symbol does not shadow the standard-library type in files that
    /// import the generated module. `SwiftROS2GenPlugin` keeps a copy of this set, which
    /// `PluginNamingTests` compares with this one.
    static let collisionTypeNames: Set<String> = [
        "Bool", "String",
        "Int", "Int8", "Int16", "Int32", "Int64",
        "UInt", "UInt8", "UInt16", "UInt32", "UInt64",
        "Float", "Float32", "Float64", "Double",
        "Empty", "Duration", "Range", "Clock",
    ]

    /// Render `ir` to Swift source.
    ///
    /// - Parameters:
    ///   - isNested: when `true`, drop `ROS2Message` conformance + the `typeInfo` constant.
    ///     Used for nested-only payloads (e.g. `Header`, `Vector3`, `UUID`) that must not be
    ///     advertised as a top-level topic.
    ///   - structNameOverride: when non-nil, overrides the default
    ///     ``swiftStructName(typeName:)`` mapping. Used to prefix cross-package collisions like
    ///     `unique_identifier_msgs/UUID` → `UniqueIdentifierUUID`.
    ///   - nestedNameOverrides: per-reference Swift-name overrides keyed by
    ///     `<package>/msg/<TypeName>`. When a nested field's full ROS name is in the map, the
    ///     mapped value wins over ``swiftStructName(typeName:)``.
    public static func emit(
        _ ir: MessageIR,
        sourceLabel: String,
        isNested: Bool = false,
        structNameOverride: String? = nil,
        nestedNameOverrides: [String: String] = [:],
        moduleNames: ModuleNames = [:]
    ) -> String {
        var out = ""
        out += "// Generated by swift-ros2-gen \u{2014} DO NOT EDIT.\n"
        out += "// Source: \(sourceLabel)\n"
        out += "\n"
        out += ModuleImports.importLines(
            ownPackage: ir.package, fieldTypes: ir.fields.map(\.type),
            moduleNames: moduleNames)
        out += "\n"
        out += emitMessageStruct(
            ir,
            isNested: isNested,
            structNameOverride: structNameOverride,
            nestedNameOverrides: nestedNameOverrides)
        return out
    }

    /// Emit a single `public struct …` declaration for `ir` without the file
    /// header / imports. Used by both the top-level message emit (which
    /// prefixes its own header) and the action emit (which composes multiple
    /// wrapper structs into one file).
    static func emitMessageStruct(
        _ ir: MessageIR,
        isNested: Bool,
        structNameOverride: String?,
        nestedNameOverrides: [String: String]
    ) -> String {
        let conditional = !isNested && isConditional(ir)
        let read = readDistros(ir)
        let ladder = isNested ? [] : modernLadder(ir.perDistroHashes, read: Set(ir.perDistroFieldPresence.keys))
        var out = ""
        out += "/// \(ir.rosTypeName)\n"
        let structName = structNameOverride ?? swiftStructName(typeName: ir.typeName)
        let conformance =
            isNested ? "CDRCodable, Equatable, Sendable" : "ROS2Message, Equatable, Sendable"
        out += "public struct \(structName): \(conformance) {\n"

        var preludeEmitted = false
        if !isNested {
            if ladder.count > 1 {
                out += emitTypeInfoLadder(ir, ladder: ladder)
                preludeEmitted = true
            } else if conditional {
                out += emitTypeInfoFactory(ir)
                preludeEmitted = true
            } else {
                guard
                    let hashOpt = ir.perDistroHashes["jazzy"],
                    let hash = hashOpt
                else {
                    preconditionFailure(
                        "MessageIR for \(ir.rosTypeName) is missing the 'jazzy' type hash")
                }
                out += "    public static let typeInfo = ROS2MessageTypeInfo(\n"
                out += "        typeName: \"\(ir.rosTypeName)\",\n"
                out += "        typeHash: \"\(hash)\"\n"
                out += "    )\n"
                preludeEmitted = true
            }
        }

        if !ir.constants.isEmpty {
            if preludeEmitted {
                out += "\n"
            }
            for c in ir.constants {
                // ROS constants are conventionally UPPER_SNAKE; opt out of swift-format's
                // lowerCamelCase rule per-line so generated files lint cleanly.
                out += "    // swift-format-ignore: AlwaysUseLowerCamelCase\n"
                out += "    public static let \(c.swiftName): "
                out += "\(c.type.swiftTypeName) = \(swiftLiteral(c.value))\n"
            }
            preludeEmitted = true
        }

        if ir.fields.isEmpty {
            if preludeEmitted {
                out += "\n"
            }
            out += "    public init() {}\n"
            out += "\n"
            // Every empty rosidl struct — message, service half or action part — carries
            // the implicit `uint8 structure_needs_at_least_one_member`
            // sentinel, and rosidl SERIALIZES it (one 0x00 body byte after
            // the encapsulation header). The RIHS01 hasher already models the
            // sentinel field; the codec must match or an empty publish
            // under-runs every rosidl-based subscriber by one byte.
            out += "    public func encode(to encoder: CDREncoder) throws {\n"
            out += "        encoder.writeUInt8(0)\n"
            out += "    }\n"
            out += "\n"
            out += "    public init(from decoder: CDRDecoder) throws {\n"
            out += "        _ = try decoder.readUInt8()\n"
            out += "    }\n"
        } else {
            if preludeEmitted {
                out += "\n"
            }
            for field in ir.fields {
                if let comment = boundedComment(field.type) {
                    out += "    \(comment)\n"
                }
                out += availabilityDoc(field, read: read, nestedNameOverrides: nestedNameOverrides, indent: "    ")
                let typeName = swiftType(field.type, nestedNameOverrides: nestedNameOverrides)
                out += "    public var \(field.swiftName): \(typeName)\n"
            }
            out += "\n"
            if ir.fields.count == 1, let field = ir.fields.first {
                let typeName = swiftType(field.type, nestedNameOverrides: nestedNameOverrides)
                let defaultVal = initDefault(field, nestedNameOverrides: nestedNameOverrides)
                out += "    public init(\(field.swiftName): \(typeName) = \(defaultVal)) {\n"
                out += "        self.\(field.swiftName) = \(field.swiftName)\n"
            } else {
                out += "    public init(\n"
                for (i, field) in ir.fields.enumerated() {
                    let comma = i == ir.fields.count - 1 ? "" : ","
                    let typeName = swiftType(field.type, nestedNameOverrides: nestedNameOverrides)
                    let defaultVal = initDefault(field, nestedNameOverrides: nestedNameOverrides)
                    out += "        \(field.swiftName): \(typeName) = \(defaultVal)\(comma)\n"
                }
                out += "    ) {\n"
                for field in ir.fields {
                    out += "        self.\(field.swiftName) = \(field.swiftName)\n"
                }
            }
            out += "    }\n"
            out += "\n"
            out += "    public func encode(to encoder: CDREncoder) throws {\n"
            for field in ir.fields {
                out += emitEncodeWithAvailability(field, read: read)
            }
            out += "    }\n"
            out += "\n"
            out += "    public init(from decoder: CDRDecoder) throws {\n"
            for field in ir.fields {
                out += emitDecodeWithAvailability(
                    field, nestedNameOverrides: nestedNameOverrides, read: read)
            }
            out += "    }\n"
        }
        out += "}\n"
        return out
    }

    /// Render a `ROS2ServiceType` umbrella enum that ties the previously-emitted
    /// request / response struct halves together. The umbrella owns the canonical
    /// `<pkg>/srv/<Service>` `serviceName`, the per-half RIHS01 hashes and the
    /// service-level hash (`serviceHash`, see ``ServiceDescription``); the
    /// halves themselves carry their own `<pkg>/srv/<Service>_Request|Response`
    /// `typeInfo` (so they are usable as standalone messages too, which is what
    /// the wire layer hands to publishers / subscriptions internally).
    public static func emitServiceUmbrella(
        package: String,
        serviceTypeName: String,
        umbrellaName: String,
        requestStructName: String,
        responseStructName: String,
        requestHash: String?,
        responseHash: String?,
        serviceHash: String? = nil,
        sourceLabel: String,
        moduleNames: ModuleNames = [:]
    ) -> String {
        var typeInfo = ""
        typeInfo += "    public static let typeInfo = ROS2ServiceTypeInfo(\n"
        typeInfo += serviceInfoArguments(
            package: package, serviceTypeName: serviceTypeName,
            hashes: ServiceHashes(requestHash: requestHash, responseHash: responseHash, serviceHash: serviceHash),
            indent: "        ")
        typeInfo += "    )\n"
        return serviceUmbrella(
            package: package, serviceTypeName: serviceTypeName, umbrellaName: umbrellaName,
            requestStructName: requestStructName, responseStructName: responseStructName,
            typeInfo: typeInfo, sourceLabel: sourceLabel, moduleNames: moduleNames)
    }

    /// Render a `ROS2ServiceType` umbrella enum from the hashes of each distribution
    /// (`hashesByDistro`, keyed by distribution name, with at least `"jazzy"`).
    ///
    /// When every modern distribution has the same hashes, this is
    /// ``emitServiceUmbrella(package:serviceTypeName:umbrellaName:requestStructName:responseStructName:requestHash:responseHash:serviceHash:sourceLabel:moduleNames:)``
    /// with the Jazzy hashes. Otherwise the umbrella gets `typeInfo(for:)`, returning one
    /// ``ROS2ServiceTypeInfo`` per change of hashes in release order (a distribution not in
    /// `hashesByDistro` takes those of its schema distribution, see
    /// ``IRBuilder/schemaDistro(for:read:)``), and `typeInfo` returns the Jazzy one.
    public static func emitServiceUmbrella(
        package: String,
        serviceTypeName: String,
        umbrellaName: String,
        requestStructName: String,
        responseStructName: String,
        hashesByDistro: [String: ServiceHashes],
        sourceLabel: String,
        moduleNames: ModuleNames = [:]
    ) -> String {
        let ladder = modernLadder(hashesByDistro, read: [])
        guard ladder.count > 1 else {
            let hashes =
                hashesByDistro["jazzy"] ?? ladder.first?.value
                ?? ServiceHashes(requestHash: nil, responseHash: nil, serviceHash: nil)
            return emitServiceUmbrella(
                package: package, serviceTypeName: serviceTypeName, umbrellaName: umbrellaName,
                requestStructName: requestStructName, responseStructName: responseStructName,
                requestHash: hashes.requestHash, responseHash: hashes.responseHash,
                serviceHash: hashes.serviceHash, sourceLabel: sourceLabel, moduleNames: moduleNames)
        }
        let typeInfo = emitInfoLadder(
            infoType: "ROS2ServiceTypeInfo", ladder: ladder,
            arguments: { hashes, indent in
                serviceInfoArguments(
                    package: package, serviceTypeName: serviceTypeName, hashes: hashes, indent: indent)
            })
        return serviceUmbrella(
            package: package, serviceTypeName: serviceTypeName, umbrellaName: umbrellaName,
            requestStructName: requestStructName, responseStructName: responseStructName,
            typeInfo: typeInfo, sourceLabel: sourceLabel, moduleNames: moduleNames)
    }

    /// A service umbrella file around its `typeInfo` declaration(s).
    private static func serviceUmbrella(
        package: String,
        serviceTypeName: String,
        umbrellaName: String,
        requestStructName: String,
        responseStructName: String,
        typeInfo: String,
        sourceLabel: String,
        moduleNames: ModuleNames
    ) -> String {
        var out = ""
        out += "// Generated by swift-ros2-gen \u{2014} DO NOT EDIT.\n"
        out += "// Source: \(sourceLabel)\n"
        out += "\n"
        // The umbrella only declares `typeInfo` and two typealiases, so it needs no CDR import.
        out += ModuleImports.imports(ownPackage: package, fieldTypes: [], moduleNames: moduleNames)
            .map { "import \($0)\n" }.joined()
        out += "\n"
        out += "/// \(package)/srv/\(serviceTypeName)\n"
        out += "public enum \(umbrellaName): ROS2ServiceType {\n"
        out += typeInfo
        out += "\n"
        out += "    public typealias Request = \(requestStructName)\n"
        out += "    public typealias Response = \(responseStructName)\n"
        out += "}\n"
        return out
    }

    /// The argument lines of a `ROS2ServiceTypeInfo(…)` call, each prefixed with `indent`.
    private static func serviceInfoArguments(
        package: String, serviceTypeName: String, hashes: ServiceHashes, indent: String
    ) -> String {
        [
            "serviceName: \"\(package)/srv/\(serviceTypeName)\",",
            "requestTypeName: \"\(package)/srv/\(serviceTypeName)_Request\",",
            "responseTypeName: \"\(package)/srv/\(serviceTypeName)_Response\",",
            "requestTypeHash: \(swiftOptionalString(hashes.requestHash)),",
            "responseTypeHash: \(swiftOptionalString(hashes.responseHash)),",
            "serviceTypeHash: \(swiftOptionalString(hashes.serviceHash))",
        ].map { "\(indent)\($0)\n" }.joined()
    }

    /// `static func typeInfo(for:)` returning one `<infoType>` per step of `ladder` (newest
    /// first, `withoutTypeHashes` of the Jazzy one where the distribution has no RIHS01 hashes),
    /// plus `static var typeInfo`, the Jazzy one. `arguments` renders the initializer arguments
    /// of a step's value at an indent.
    private static func emitInfoLadder<Value>(
        infoType: String, ladder: [(since: String, value: Value)],
        arguments: (Value, String) -> String
    ) -> String {
        var out = ""
        out += "    public static func typeInfo(for distro: ROS2Distro) -> \(infoType) {\n"
        out += "        if !distro.supportsTypeHash {\n"
        out += "            return typeInfo(for: .jazzy).withoutTypeHashes\n"
        for (i, step) in ladder.enumerated().reversed() {
            out += i == 0 ? "        } else {\n" : "        } else if distro >= .\(step.since) {\n"
            out += "            return \(infoType)(\n"
            out += arguments(step.value, "                ")
            out += "            )\n"
        }
        out += "        }\n"
        out += "    }\n"
        out += "\n"
        out += "    public static var typeInfo: \(infoType) { typeInfo(for: .jazzy) }\n"
        return out
    }

    /// Render an ``ActionIR`` to a single Swift source file.
    ///
    /// Layout:
    /// 1. Header (`// Generated by swift-ros2-gen` + source label) + imports.
    /// 2. One outer `public enum <TypeName>Action: ROS2Action` carrying the
    ///    static `typeInfo` and three inner `Goal` / `Result` / `Feedback`
    ///    structs (each conforms to `CDRCodable, Equatable, Sendable` — they
    ///    are nested-only payloads, never advertised at the topic level).
    /// 3. Five sibling top-level `public struct <Action>_<Wrapper>` definitions
    ///    that conform to ``ROS2Message`` — these are the wire types that
    ///    publishers / subscribers actually exchange.
    ///
    /// The five wrappers are emitted via ``emit(_:sourceLabel:isNested:structNameOverride:nestedNameOverrides:)``
    /// so per-wrapper bodies share the message emitter's logic. Cross-wrapper
    /// references to the inner Goal/Result/Feedback structs are routed through
    /// `nestedNameOverrides` (e.g.
    /// `example_interfaces/action/Fibonacci_Goal -> FibonacciAction.Goal`).
    public static func emit(
        _ ir: ActionIR,
        sourceLabel: String,
        nestedNameOverrides: [String: String] = [:],
        moduleNames: ModuleNames = [:]
    ) -> String {
        guard let hashes = ir.perDistroHashes["jazzy"] else {
            preconditionFailure(
                "ActionIR for \(ir.rosActionName) is missing the 'jazzy' hash bundle")
        }
        let ladder = modernLadder(ir.perDistroHashes, read: [])

        // Local overrides so wrappers nest the correct enum-scoped names.
        var overrides = nestedNameOverrides
        let actionEnumName = "\(ir.typeName)Action"
        overrides["\(ir.package)/action/\(ir.typeName)_Goal"] =
            "\(actionEnumName).Goal"
        overrides["\(ir.package)/action/\(ir.typeName)_Result"] =
            "\(actionEnumName).Result"
        overrides["\(ir.package)/action/\(ir.typeName)_Feedback"] =
            "\(actionEnumName).Feedback"

        var out = ""
        out += "// Generated by swift-ros2-gen \u{2014} DO NOT EDIT.\n"
        out += "// Source: \(sourceLabel)\n"
        out += "\n"
        let actionFieldTypes = [
            ir.goal, ir.result, ir.feedback,
            ir.sendGoalRequest, ir.sendGoalResponse,
            ir.getResultRequest, ir.getResultResponse,
            ir.feedbackMessage,
        ].flatMap { $0.fields.map(\.type) }
        out += ModuleImports.importLines(
            ownPackage: ir.package, fieldTypes: actionFieldTypes,
            moduleNames: moduleNames)
        out += "\n"

        // Outer ROS2Action enum.
        out += "/// \(ir.rosActionName)\n"
        out += "public enum \(actionEnumName): ROS2Action {\n"
        if ladder.count > 1 {
            // The goal, result or feedback reaches a type whose fields differ among modern
            // distributions: one hash bundle per change.
            out += emitInfoLadder(
                infoType: "ROS2ActionTypeInfo", ladder: ladder,
                arguments: { actionInfoArguments(ir, hashes: $0, indent: $1) })
        } else {
            out += "    public static let typeInfo = ROS2ActionTypeInfo(\n"
            out += actionInfoArguments(ir, hashes: hashes, indent: "        ")
            out += "    )\n"
        }
        out += "\n"
        out += emitActionInnerStruct(
            name: "Goal", fields: ir.goal.fields,
            indent: "    ", nestedNameOverrides: overrides)
        out += "\n"
        out += emitActionInnerStruct(
            name: "Result", fields: ir.result.fields,
            indent: "    ", nestedNameOverrides: overrides)
        out += "\n"
        out += emitActionInnerStruct(
            name: "Feedback", fields: ir.feedback.fields,
            indent: "    ", nestedNameOverrides: overrides)
        out += "}\n"
        out += "\n"

        // Five top-level wrapper structs. Reuses ``emitMessageStruct`` so each
        // wrapper's body stays identical to a normal `.msg`-derived struct
        // (without re-emitting the file header / imports for every wrapper).
        for (i, wrapper) in [
            ir.sendGoalRequest, ir.sendGoalResponse,
            ir.getResultRequest, ir.getResultResponse,
            ir.feedbackMessage,
        ].enumerated() {
            if i > 0 {
                out += "\n"
            }
            out += emitMessageStruct(
                wrapper,
                isNested: false,
                structNameOverride: nil,
                nestedNameOverrides: overrides
            )
        }
        return out
    }

    /// The argument lines of a `ROS2ActionTypeInfo(…)` call, each prefixed with `indent`.
    private static func actionInfoArguments(_ ir: ActionIR, hashes: ActionHashes, indent: String) -> String {
        [
            "actionName: \"\(ir.rosActionName)\",",
            "goalTypeHash: \"\(hashes.goalHash)\",",
            "resultTypeHash: \"\(hashes.resultHash)\",",
            "feedbackTypeHash: \"\(hashes.feedbackHash)\",",
            "sendGoalRequestTypeHash: \"\(hashes.sendGoalRequestHash)\",",
            "sendGoalResponseTypeHash: \"\(hashes.sendGoalResponseHash)\",",
            "getResultRequestTypeHash: \"\(hashes.getResultRequestHash)\",",
            "getResultResponseTypeHash: \"\(hashes.getResultResponseHash)\",",
            "feedbackMessageTypeHash: \"\(hashes.feedbackMessageHash)\",",
            "sendGoalServiceTypeHash: \(swiftOptionalString(hashes.sendGoalServiceHash)),",
            "getResultServiceTypeHash: \(swiftOptionalString(hashes.getResultServiceHash))",
        ].map { "\(indent)\($0)\n" }.joined()
    }

    /// Emit a `Goal` / `Result` / `Feedback` inner struct (CDRCodable, no
    /// `ROS2Message` conformance — like any other ``CDRCodable`` body, the
    /// generated `encode(to:)` writes only the message body; the CDR
    /// encapsulation header is prepended by the caller (the publish path)
    /// and these inner payloads are never published directly).
    static func emitActionInnerStruct(
        name: String,
        fields: [FieldIR],
        indent: String,
        nestedNameOverrides: [String: String]
    ) -> String {
        var out = ""
        out += "\(indent)public struct \(name): CDRCodable, Equatable, Sendable {\n"
        if fields.isEmpty {
            // rosidl gives an empty goal / result / feedback the same implicit
            // `uint8 structure_needs_at_least_one_member` as any other empty
            // structure (see ``emitMessageStruct``) and serializes it, so the
            // codec writes and reads one 0x00 body byte here too.
            out += "\(indent)    public init() {}\n"
            out += "\n"
            out += "\(indent)    public func encode(to encoder: CDREncoder) throws {\n"
            out += "\(indent)        encoder.writeUInt8(0)\n"
            out += "\(indent)    }\n"
            out += "\n"
            out += "\(indent)    public init(from decoder: CDRDecoder) throws {\n"
            out += "\(indent)        _ = try decoder.readUInt8()\n"
            out += "\(indent)    }\n"
        } else {
            for field in fields {
                if let comment = boundedComment(field.type) {
                    out += "\(indent)    \(comment)\n"
                }
                let typeName = swiftType(field.type, nestedNameOverrides: nestedNameOverrides)
                out += "\(indent)    public var \(field.swiftName): \(typeName)\n"
            }
            out += "\n"
            if fields.count == 1, let f = fields.first {
                let typeName = swiftType(f.type, nestedNameOverrides: nestedNameOverrides)
                let defaultVal = initDefault(f, nestedNameOverrides: nestedNameOverrides)
                out += "\(indent)    public init(\(f.swiftName): \(typeName) = \(defaultVal)) {\n"
                out += "\(indent)        self.\(f.swiftName) = \(f.swiftName)\n"
            } else {
                out += "\(indent)    public init(\n"
                for (i, f) in fields.enumerated() {
                    let comma = i == fields.count - 1 ? "" : ","
                    let typeName = swiftType(f.type, nestedNameOverrides: nestedNameOverrides)
                    let defaultVal = initDefault(f, nestedNameOverrides: nestedNameOverrides)
                    out +=
                        "\(indent)        \(f.swiftName): \(typeName) = \(defaultVal)\(comma)\n"
                }
                out += "\(indent)    ) {\n"
                for f in fields {
                    out += "\(indent)        self.\(f.swiftName) = \(f.swiftName)\n"
                }
            }
            out += "\(indent)    }\n"
            out += "\n"
            out += "\(indent)    public func encode(to encoder: CDREncoder) throws {\n"
            for f in fields {
                let body = emitEncodeWithAvailability(f)
                out += reindent(body, by: indent)
            }
            out += "\(indent)    }\n"
            out += "\n"
            out += "\(indent)    public init(from decoder: CDRDecoder) throws {\n"
            for f in fields {
                let body = emitDecodeWithAvailability(
                    f, nestedNameOverrides: nestedNameOverrides)
                out += reindent(body, by: indent)
            }
            out += "\(indent)    }\n"
        }
        out += "\(indent)}\n"
        return out
    }

    /// Reindent a multi-line emitted body (originally indented for a top-level
    /// struct, i.e. 8 spaces inside the encode/decode method bodies) by an
    /// extra `prefix`. Empty lines stay empty.
    static func reindent(_ body: String, by prefix: String) -> String {
        return
            body
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { line -> String in
                line.isEmpty ? "" : prefix + String(line)
            }
            .joined(separator: "\n")
    }

    private static func swiftOptionalString(_ s: String?) -> String {
        guard let s = s else { return "nil" }
        return "\"\(s)\""
    }

    /// Find the override-map key for a nested reference. Tries each
    /// ``MessageKind`` raw value (`msg`, `srv`, `action`) so callers can store
    /// overrides keyed by the actual canonical ROS type name regardless of the
    /// referenced type's family. Falls back to the `<pkg>/msg/<Type>` key when no
    /// kind matches.
    static func nestedOverrideKey(
        package: String,
        typeName: String,
        in overrides: [String: String]
    ) -> String {
        for kind in MessageKind.allCases {
            let candidate = "\(package)/\(kind.rawValue)/\(typeName)"
            if overrides[candidate] != nil {
                return candidate
            }
        }
        return "\(package)/msg/\(typeName)"
    }

    /// Convention: append `Msg` only when the type name collides with a Swift stdlib name
    /// (or a common Swift / Foundation type such as `Empty`, `Duration` or `Range`).
    /// Anything else emits as bare PascalCase.
    public static func swiftStructName(typeName: String) -> String {
        collisionTypeNames.contains(typeName) ? typeName + "Msg" : typeName
    }

    static func swiftType(_ ft: FieldType, nestedNameOverrides: [String: String] = [:]) -> String {
        switch ft {
        case .primitive(let p): return p.swiftTypeName
        case .nested(let pkg, let typeName):
            let key = nestedOverrideKey(package: pkg, typeName: typeName, in: nestedNameOverrides)
            return nestedNameOverrides[key] ?? swiftStructName(typeName: typeName)
        case .array(let element, _):
            return "[\(swiftType(element, nestedNameOverrides: nestedNameOverrides))]"
        case .sequence(let element, _):
            return "[\(swiftType(element, nestedNameOverrides: nestedNameOverrides))]"
        case .boundedString:
            return "String"
        }
    }

    static func swiftDefault(_ ft: FieldType, nestedNameOverrides: [String: String] = [:]) -> String {
        switch ft {
        case .primitive(let p):
            switch p {
            case .bool: return "false"
            case .byte, .uint8, .char, .int8,
                .int16, .uint16, .int32, .uint32, .int64, .uint64:
                return "0"
            case .float32, .float64: return "0.0"
            case .string, .wstring: return "\"\""
            }
        case .nested(let pkg, let typeName):
            let key = nestedOverrideKey(package: pkg, typeName: typeName, in: nestedNameOverrides)
            let n = nestedNameOverrides[key] ?? swiftStructName(typeName: typeName)
            return "\(n)()"
        case .array(let element, let length):
            let inner = swiftDefault(element, nestedNameOverrides: nestedNameOverrides)
            return "Array(repeating: \(inner), count: \(length))"
        case .sequence:
            return "[]"
        case .boundedString:
            return "\"\""
        }
    }

    /// Pick the init-parameter default. Prefer the parsed `defaultValue` when set; fall back
    /// to the type-shaped zero value.
    static func initDefault(_ field: FieldIR, nestedNameOverrides: [String: String]) -> String {
        if let dv = field.defaultValue, dv != .empty {
            return swiftLiteral(dv)
        }
        return swiftDefault(field.type, nestedNameOverrides: nestedNameOverrides)
    }

    /// Render a typed default as a Swift literal (no surrounding init()).
    static func swiftLiteral(_ dv: DefaultValue) -> String {
        switch dv {
        case .bool(let b): return b ? "true" : "false"
        case .int(let n): return String(n)
        case .uint(let n): return String(n)
        case .float(let d): return String(d)
        case .string(let s): return "\"\(s)\""
        case .empty: return ""
        case .array(let xs):
            return "[" + xs.map(swiftLiteral).joined(separator: ", ") + "]"
        }
    }

    /// `// note: bounded <=N` comment for bounded string / sequence fields.
    static func boundedComment(_ ft: FieldType) -> String? {
        switch ft {
        case .boundedString(_, let upper): return "// note: bounded <=\(upper)"
        case .sequence(_, let upper?): return "// note: bounded <=\(upper)"
        default: return nil
        }
    }

    /// Whether `ir` should emit in distro-conditional mode. True when any
    /// field has non-`.all` availability, OR when the IR carries multiple
    /// distros with disagreeing hash values. A distro the IR has no hash for
    /// takes the hash of its schema distro (``IRBuilder/schemaDistro(for:read:)``).
    static func isConditional(_ ir: MessageIR) -> Bool {
        if ir.fields.contains(where: { $0.availability != .all }) { return true }
        let normalized = Set(
            ir.perDistroHashes.values.map { ($0 ?? "") }
        )
        return normalized.count > 1
    }

    /// The distributions a merged IR was read for, or nil for an IR built from one
    /// distribution's IDL (whose distro-only fields, if any, keep the Humble / modern split).
    static func readDistros(_ ir: MessageIR) -> Set<String>? {
        ir.perDistroFieldPresence.isEmpty ? nil : Set(ir.perDistroFieldPresence.keys)
    }

    /// The value each modern distribution has, in release order, as steps: each step starts at
    /// the first distribution whose value differs from the one before. A distribution missing
    /// from `values` takes the value of its schema distribution among the keys of `values` and
    /// `read` (``IRBuilder/schemaDistro(for:read:)``); one whose schema distribution has no
    /// value is skipped. One step means every modern distribution has the same value.
    static func modernLadder<Value: Equatable>(
        _ values: [String: Value], read: Set<String>
    ) -> [(since: String, value: Value)] {
        let known = Set(values.keys).union(read)
        var ladder: [(since: String, value: Value)] = []
        for distro in IRBuilder.modernDistros {
            let key = values[distro] != nil ? distro : IRBuilder.schemaDistro(for: distro, read: known)
            guard let value = values[key] else { continue }
            if let last = ladder.last, last.value == value { continue }
            ladder.append((distro, value))
        }
        return ladder
    }

    /// Emit `static func typeInfo(for distro:)` with one hash per step of `ladder` (newest
    /// first, `nil` where the distribution has no RIHS01 hashes) plus the `static var typeInfo`
    /// shim, for a type whose hash differs among modern distributions. Comparing with the
    /// distribution where the hash changes keeps the file correct when a distribution is added.
    static func emitTypeInfoLadder(_ ir: MessageIR, ladder: [(since: String, value: String?)]) -> String {
        var out = ""
        out += "    public static func typeInfo(for distro: ROS2Distro) -> ROS2MessageTypeInfo {\n"
        out += "        let typeHash: String?\n"
        out += "        if !distro.supportsTypeHash {\n"
        out += "            typeHash = nil\n"
        for (i, step) in ladder.enumerated().reversed() {
            out += i == 0 ? "        } else {\n" : "        } else if distro >= .\(step.since) {\n"
            out += "            typeHash = \(quotedOrNil(step.value))\n"
        }
        out += "        }\n"
        out += "        return ROS2MessageTypeInfo(\n"
        out += "            typeName: \"\(ir.rosTypeName)\",\n"
        out += "            typeHash: typeHash\n"
        out += "        )\n"
        out += "    }\n"
        out += "\n"
        out += "    public static var typeInfo: ROS2MessageTypeInfo { typeInfo(for: .jazzy) }\n"
        return out
    }

    /// Emit `static func typeInfo(for distro:)` plus the `static var typeInfo` shim.
    ///
    /// For a type whose modern distributions share one hash, so it differs only on Humble:
    /// legacy (Humble, no hash) and modern (every later distribution). Branching on
    /// `isLegacySchema` instead of switching over `ROS2Distro` keeps the file compiling when a
    /// distribution is added. A type whose hash differs among modern distributions gets
    /// ``emitTypeInfoLadder(_:ladder:)`` instead.
    static func emitTypeInfoFactory(_ ir: MessageIR) -> String {
        let legacyHash = ir.perDistroHashes["humble"] ?? nil
        let modernHash = IRBuilder.modernDistros.lazy.compactMap { ir.perDistroHashes[$0] ?? nil }.first
        var out = ""
        out += "    public static func typeInfo(for distro: ROS2Distro) -> ROS2MessageTypeInfo {\n"
        out += "        ROS2MessageTypeInfo(\n"
        out += "            typeName: \"\(ir.rosTypeName)\",\n"
        // swift-format's layout for a ternary that does not fit on one line: a RIHS01 hash
        // after `typeHash: distro.isLegacySchema ? nil : ` exceeds the 120-column limit.
        out += "            typeHash: distro.isLegacySchema\n"
        out += "                ? \(quotedOrNil(legacyHash)) : \(quotedOrNil(modernHash))\n"
        out += "        )\n"
        out += "    }\n"
        out += "\n"
        out += "    public static var typeInfo: ROS2MessageTypeInfo { typeInfo(for: .jazzy) }\n"
        return out
    }

    static func quotedOrNil(_ value: String?) -> String {
        guard let v = value, !v.isEmpty else { return "nil" }
        return "\"\(v)\""
    }

    /// Which distributions encode a field that only some distributions have.
    enum FieldGuard: Equatable {
        /// Humble only: `isLegacySchema`.
        case legacyOnly
        /// Every distribution after Humble: `!isLegacySchema`.
        case modernOnly
        /// From `since` (included) up to `until` (excluded), compared with the codec's
        /// `schemaDistro`; a nil bound is open.
        case bounded(since: String?, until: String?)
    }

    /// The guard of a field present in `present` of the distributions `read` (nil for a field
    /// of a single-distribution IR). `since` is the first read distribution that has the field,
    /// omitted when the oldest has it; `until` is the first read distribution after them that
    /// lacks it, omitted when the newest has it. A field split exactly between Humble and
    /// Jazzy keeps the `isLegacySchema` guard of 1.0.
    static func fieldGuard(present: Set<String>, read: Set<String>?) -> FieldGuard {
        precondition(!present.isEmpty, "FieldAvailability.onlyIn must contain at least one distro")
        let known = Set(IRBuilder.distroOrder)
        precondition(
            present.allSatisfy(known.contains),
            "FieldAvailability.onlyIn contains unknown distro(s): \(present)")
        guard let read else { return present == ["humble"] ? .legacyOnly : .modernOnly }
        let ordered = IRBuilder.distroOrder.filter(read.contains)
        guard let first = ordered.firstIndex(where: present.contains),
            let last = ordered.lastIndex(where: present.contains)
        else {
            preconditionFailure("FieldAvailability.onlyIn \(present) has none of the read distros \(read)")
        }
        let since = first > 0 ? ordered[first] : nil
        let until = last < ordered.count - 1 ? ordered[last + 1] : nil
        switch (since, until) {
        case ("jazzy", nil): return .modernOnly  // ordered[0] is Humble
        case (nil, "jazzy"): return .legacyOnly  // the field is Humble's alone
        default: return .bounded(since: since, until: until)
        }
    }

    /// The `if` condition of `guard` on the codec named `codec` (`encoder` / `decoder`), or nil
    /// when the guard admits every distribution.
    static func guardCondition(_ guard: FieldGuard, codec: String) -> String? {
        switch `guard` {
        case .legacyOnly: return "\(codec).isLegacySchema"
        case .modernOnly: return "!\(codec).isLegacySchema"
        case .bounded(let since, let until):
            var parts: [String] = []
            if let since { parts.append("\(codec).schemaDistro >= .\(since)") }
            if let until { parts.append("\(codec).schemaDistro < .\(until)") }
            return parts.isEmpty ? nil : parts.joined(separator: " && ")
        }
    }

    /// The doc comment of a field that only some modern distributions have, at `indent`: the
    /// distributions that have it and what it decodes as elsewhere. Empty for a field every
    /// distribution has and for a field split between Humble and Jazzy.
    static func availabilityDoc(
        _ field: FieldIR, read: Set<String>?, nestedNameOverrides: [String: String], indent: String
    ) -> String {
        guard case .onlyIn(let present) = field.availability,
            case .bounded(let since, let until) = fieldGuard(present: present, read: read)
        else { return "" }
        func name(_ distro: String) -> String { distro.prefix(1).uppercased() + distro.dropFirst() }
        let which: String
        let elsewhere: String
        switch (since, until) {
        case (let since?, nil):
            which = "\(name(since)) and later only."
            elsewhere = "Not encoded for an earlier distribution;"
        case (nil, let until?):
            which = "Before \(name(until)) only."
            elsewhere = "Not encoded for \(name(until)) and later;"
        case (let since?, let until?):
            which = "\(name(since)) and later, before \(name(until)), only."
            elsewhere = "Not encoded for other distributions;"
        case (nil, nil):
            return ""
        }
        let decoded = "decoded there as `\(initDefault(field, nestedNameOverrides: nestedNameOverrides))`."
        let line = "\(indent)/// \(which) \(elsewhere) \(decoded)"
        if line.count <= 120 { return line + "\n" }
        return "\(indent)/// \(which) \(elsewhere)\n\(indent)/// \(decoded)\n"
    }

    /// Indent each non-empty line of an emitted body by four more spaces.
    private static func indented(_ body: String) -> String {
        body
            .split(separator: "\n", omittingEmptySubsequences: false)
            .map { line -> String in
                line.isEmpty ? "" : "    " + String(line)
            }
            .joined(separator: "\n")
    }

    /// Encode a field, wrapping the body in a guard (see ``fieldGuard(present:read:)``) when
    /// availability marks it as distro-conditional:
    ///   - split between Humble and Jazzy: `if !encoder.isLegacySchema` for a field from Jazzy
    ///     on, `if encoder.isLegacySchema` for a field Humble alone has, as in 1.0;
    ///   - any other run of the read distributions `read`: `if encoder.schemaDistro >= .lyrical`,
    ///     `< .lyrical`, or both bounds.
    static func emitEncodeWithAvailability(_ field: FieldIR, read: Set<String>? = nil) -> String {
        switch field.availability {
        case .all:
            return emitEncode(field)
        case .onlyIn(let distros):
            guard let condition = guardCondition(fieldGuard(present: distros, read: read), codec: "encoder") else {
                return emitEncode(field)
            }
            var out = "        if \(condition) {\n"
            out += indented(emitEncode(field))
            out += "        }\n"
            return out
        }
    }

    /// Decode a field, branching like ``emitEncodeWithAvailability(_:read:)`` when availability
    /// marks it as distro-conditional. The branch for the distributions without the field sets
    /// it to its init default (the IDL default, else zero); the other branch decodes it.
    static func emitDecodeWithAvailability(
        _ field: FieldIR,
        nestedNameOverrides: [String: String],
        read: Set<String>? = nil
    ) -> String {
        switch field.availability {
        case .all:
            return emitDecode(field, nestedNameOverrides: nestedNameOverrides)
        case .onlyIn(let distros):
            let fieldGuard = fieldGuard(present: distros, read: read)
            guard let condition = guardCondition(fieldGuard, codec: "decoder") else {
                return emitDecode(field, nestedNameOverrides: nestedNameOverrides)
            }
            let defaultExpr = initDefault(field, nestedNameOverrides: nestedNameOverrides)
            let body = indented(emitDecode(field, nestedNameOverrides: nestedNameOverrides))
            let absent = "            self.\(field.swiftName) = \(defaultExpr)\n"
            var out = ""
            if fieldGuard == .modernOnly {
                // 1.0 shape: the legacy branch first.
                out += "        if decoder.isLegacySchema {\n"
                out += absent
                out += "        } else {\n"
                out += body
            } else {
                out += "        if \(condition) {\n"
                out += body
                out += "        } else {\n"
                out += absent
            }
            out += "        }\n"
            return out
        }
    }

    static func emitEncode(_ field: FieldIR) -> String {
        switch field.type {
        case .primitive:
            return "        encoder.\(writerCall(field.type))(\(field.swiftName))\n"
        case .nested:
            return "        try \(field.swiftName).encode(to: encoder)\n"
        case .array(let element, let length):
            // Fixed array: reject a value whose length is not the IDL length, then a
            // per-element loop with no length prefix on the wire.
            var out = "        guard \(field.swiftName).count == \(length) else {\n"
            out += "            throw CDRSerializationError.invalidArrayLength(\n"
            out +=
                "                field: \"\(field.swiftName)\", expected: \(length), actual: \(field.swiftName).count)\n"
            out += "        }\n"
            out += "        for v in \(field.swiftName) {\n"
            out += elementEncodeLines(element, value: "v", field: field.swiftName, indent: "            ")
            out += "        }\n"
            return out
        case .sequence(let element, let upperBound):
            // Sequence: explicit uint32 length prefix, then per-element loop.
            // Bounded sequences reject a value longer than the IDL upper bound.
            var out = ""
            if let upper = upperBound {
                out += "        guard \(field.swiftName).count <= \(upper) else {\n"
                out += "            throw CDRSerializationError.sequenceTooLong(\n"
                out +=
                    "                field: \"\(field.swiftName)\", maximum: \(upper), actual: \(field.swiftName).count)\n"
                out += "        }\n"
            }
            // Byte-payload fast path: a sequence of `uint8` / `byte` is the
            // largest payload in many sensor messages (e.g. `CompressedImage`,
            // `PointCloud2`). `writeUInt8Sequence` does a single `Data.append`
            // instead of a per-element loop, which is materially faster on
            // multi-megabyte buffers.
            if isUInt8Like(element) {
                out += "        encoder.writeUInt8Sequence(\(field.swiftName))\n"
                return out
            }
            out += "        encoder.writeUInt32(UInt32(\(field.swiftName).count))\n"
            out += "        for v in \(field.swiftName) {\n"
            out += elementEncodeLines(element, value: "v", field: field.swiftName, indent: "            ")
            out += "        }\n"
            return out
        case .boundedString:
            return elementEncodeLines(
                field.type, value: field.swiftName, field: field.swiftName, indent: "        ")
        }
    }

    static func emitDecode(_ field: FieldIR, nestedNameOverrides: [String: String]) -> String {
        switch field.type {
        case .primitive:
            return "        self.\(field.swiftName) = try decoder.\(readerCall(field.type))()\n"
        case .nested(let pkg, let typeName):
            let key = nestedOverrideKey(package: pkg, typeName: typeName, in: nestedNameOverrides)
            let n = nestedNameOverrides[key] ?? swiftStructName(typeName: typeName)
            return "        self.\(field.swiftName) = try \(n)(from: decoder)\n"
        case .array(let element, let length):
            // Wrap in a `do { ... }` block so the local `out` and `count`
            // variables don't collide with peers when the message has
            // multiple array / sequence fields (e.g. sensor_msgs/Imu).
            let elemType = swiftType(element, nestedNameOverrides: nestedNameOverrides)
            let elem = elementDecodeExpr(element, nestedNameOverrides: nestedNameOverrides)
            var out = "        do {\n"
            out += "            var out: [\(elemType)] = []\n"
            out += "            out.reserveCapacity(\(length))\n"
            out += "            for _ in 0..<\(length) {\n"
            out += "                out.append(\(elem))\n"
            out += "            }\n"
            out += "            self.\(field.swiftName) = out\n"
            out += "        }\n"
            return out
        case .sequence(let element, let upperBound):
            // Byte-payload fast path mirroring the encoder: pull the entire
            // sequence with a single `Data` slice and bridge to `[UInt8]`.
            if isUInt8Like(element) {
                return "        self.\(field.swiftName) = Array(try decoder.readUInt8Sequence())\n"
            }
            let elemType = swiftType(element, nestedNameOverrides: nestedNameOverrides)
            let elem = elementDecodeExpr(element, nestedNameOverrides: nestedNameOverrides)
            var out = "        do {\n"
            out += "            let count = try decoder.readSequenceCount()\n"
            // Bounded sequences: reject wire payloads exceeding the IDL upper
            // bound so on-the-wire data can't decode into an out-of-spec value.
            // Mirrors the encoder-side check.
            if let upper = upperBound {
                out += "            guard count <= \(upper) else {\n"
                out +=
                    "                throw CDRDecodingError.sequenceTooLarge(elements: UInt32(count), max: \(upper))\n"
                out += "            }\n"
            }
            out += "            var out: [\(elemType)] = []\n"
            out += "            out.reserveCapacity(count)\n"
            out += "            for _ in 0..<count {\n"
            out += "                out.append(\(elem))\n"
            out += "            }\n"
            out += "            self.\(field.swiftName) = out\n"
            out += "        }\n"
            return out
        case .boundedString(_, let upper):
            return "        self.\(field.swiftName) = try decoder.readString(maxLength: \(upper))\n"
        }
    }

    /// Whether the element is `uint8` (or its `byte` alias). Used by the
    /// sequence-encoder fast path so byte-payload sequences (e.g. compressed
    /// image data) bypass the per-element loop.
    static func isUInt8Like(_ element: FieldType) -> Bool {
        if case .primitive(let p) = element {
            return p == .uint8 || p == .byte
        }
        return false
    }

    /// Encode a single value (a primitive, nested message or bounded string field, or one element
    /// of an array / sequence) as statements at `indent`, one per line. A bounded string is
    /// checked against its bound in UTF-8 bytes first, as rosidl counts it.
    static func elementEncodeLines(
        _ element: FieldType, value: String, field: String, indent: String
    ) -> String {
        let lines: [String]
        switch element {
        case .primitive:
            lines = ["encoder.\(writerCall(element))(\(value))"]
        case .nested:
            lines = ["try \(value).encode(to: encoder)"]
        case .boundedString(_, let upper):
            lines = [
                "guard \(value).utf8.count <= \(upper) else {",
                "    throw CDRSerializationError.stringTooLong(",
                "        field: \"\(field)\", maximum: \(upper), actual: \(value).utf8.count)",
                "}",
                "encoder.writeString(\(value))",
            ]
        case .array, .sequence:
            preconditionFailure("SwiftEmitter: nested array/sequence elements are not supported")
        }
        return lines.map { "\(indent)\($0)\n" }.joined()
    }

    /// Decode a single element of an array / sequence into an `.append(...)` argument.
    static func elementDecodeExpr(_ element: FieldType, nestedNameOverrides: [String: String]) -> String {
        switch element {
        case .primitive:
            return "try decoder.\(readerCall(element))()"
        case .nested(let pkg, let typeName):
            let key = nestedOverrideKey(package: pkg, typeName: typeName, in: nestedNameOverrides)
            let n = nestedNameOverrides[key] ?? swiftStructName(typeName: typeName)
            return "try \(n)(from: decoder)"
        case .boundedString(_, let upper):
            return "try decoder.readString(maxLength: \(upper))"
        case .array, .sequence:
            preconditionFailure("SwiftEmitter: nested array/sequence elements are not supported")
        }
    }

    static func writerCall(_ ft: FieldType) -> String {
        switch ft {
        case .primitive(let p):
            switch p {
            case .bool: return "writeBool"
            case .byte, .uint8: return "writeUInt8"
            case .char, .int8: return "writeInt8"
            case .int16: return "writeInt16"
            case .uint16: return "writeUInt16"
            case .int32: return "writeInt32"
            case .uint32: return "writeUInt32"
            case .int64: return "writeInt64"
            case .uint64: return "writeUInt64"
            case .float32: return "writeFloat32"
            case .float64: return "writeFloat64"
            case .string, .wstring: return "writeString"
            }
        case .nested:
            preconditionFailure("writerCall is not defined for nested types — use emitEncode")
        case .array, .sequence, .boundedString:
            preconditionFailure("writerCall is not defined for array/sequence/boundedString")
        }
    }

    static func readerCall(_ ft: FieldType) -> String {
        switch ft {
        case .primitive(let p):
            switch p {
            case .bool: return "readBool"
            case .byte, .uint8: return "readUInt8"
            case .char, .int8: return "readInt8"
            case .int16: return "readInt16"
            case .uint16: return "readUInt16"
            case .int32: return "readInt32"
            case .uint32: return "readUInt32"
            case .int64: return "readInt64"
            case .uint64: return "readUInt64"
            case .float32: return "readFloat32"
            case .float64: return "readFloat64"
            case .string, .wstring: return "readString"
            }
        case .nested:
            preconditionFailure("readerCall is not defined for nested types — use emitDecode")
        case .array, .sequence, .boundedString:
            preconditionFailure("readerCall is not defined for array/sequence/boundedString")
        }
    }
}
